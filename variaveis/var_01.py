def nomeFuncao(argumento_1):

    var = 0x01 #Variavel local, existem somente dentro da funcao
    '''Definindo var em forma hexadecimal que equivale na base decimal ao numero 1

    '''
    return var*argumento_1 #Retorna o produto de argumentos locais.


print(nomeFuncao(10))
print(nomeFuncao(7.5))
print(nomeFuncao(3.3))
print(nomeFuncao(11.5))
